      const w = (width - 0.23) / columns;
      const xx = x + 0.12 + col * w;
      const h = 0.26 + ((col + row) % 3) * 0.06;
      b.box([xx, y + 0.077, z + 0.14], [w * 0.76, h, 0.25], colors[(col * 3 + row) % colors.length]);
