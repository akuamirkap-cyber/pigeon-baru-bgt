  b.box([x - size / 2 - 0.025, y + 0.37, z - size / 2 - 0.025], [size + 0.05, 0.12, size + 0.05], P.woodLight);
  b.box([x - size / 2 + 0.08, y + 0.48, z - size / 2 + 0.08], [size - 0.16, 0.035, size - 0.16], '#544336');
