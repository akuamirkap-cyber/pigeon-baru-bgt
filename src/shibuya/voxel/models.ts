const cache = new Map<string, AssetData>();

export function getAssetData(id: AssetId, focus?: string | null): AssetData {
  const key = `${id}:${isPackAsset(id) ? focus ?? 'all' : 'all'}`;
  if (!cache.has(key)) {
    const data = id === 'characters' ? buildCharacters(focus) : id === 'vehicles' ? buildVehicles(focus)
      : id === 'animals' ? buildAnimals(focus) : id === 'konbini' ? konbini() : id === 'ramen' ? ramen() : createLandmark(id);
    cache.set(key, data);
  }
  return cache.get(key)!;
}