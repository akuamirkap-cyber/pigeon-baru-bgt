import { Builder, P } from './builder';
import { airConditioner, base, bush } from './landmarkKit';

function window(b: Builder, x: number, y: number, z: number, width: number, height: number, wood = false) {
  b.box([x, y, z], [width, height, 0.065], wood ? '#705138' : '#617f82');
  b.box([x + 0.07, y + 0.07, z + 0.068], [width - 0.14, height - 0.14, 0.02], '#a7d6cd', { glow: 0.13 });
  const count = wood ? 5 : 2;
  for (let i = 1; i < count; i++) b.box([x + i * width / count - 0.016, y + 0.06, z + 0.092], [0.032, height - 0.12, 0.028], wood ? '#936a3e' : '#e4e6d5');
  if (wood) b.box([x, y + height / 2, z + 0.097], [width, 0.036, 0.027], '#936a3e');
}

function tileRoof(b: Builder, y: number, width: number, depth: number, color: string) {
  for (let step = 0; step < 7; step++) {
    const inset = step * 0.36;
    b.box([-width / 2 + inset, y + step * 0.17, -depth / 2 - 0.22], [width - inset * 2, 0.145, depth + 0.44], color);
    for (let i = 0; i < 14; i++) {
      b.box([-width / 2 + inset + 0.12, y + step * 0.17 + 0.146, -depth / 2 - 0.18 + i * (depth + 0.3) / 14],
        [width - inset * 2 - 0.24, 0.018, 0.029], step % 2 ? '#657878' : '#55696c');
    }
  }
  b.box([-0.24, y + 1.19, -depth / 2 - 0.25], [0.48, 0.14, depth + 0.5], '#526769');
}

export function buildMachiya() {
  const b = new Builder();
  base(b, 'machiya', 10.3, 9.8, true);
  b.part = 'setting';
  bush(b, -3.8, 2.1, 0.9);
  bush(b, 3.7, 2.3, 0.8);
  b.part = 'store';
  b.box([-2.58, 0.73, -2.24], [5.16, 0.24, 4.48], '#a7ab95');
  b.box([-2.5, 0.97, -2.12], [5, 4.88, 4.24], '#e5d8b8');
  for (const x of [-2.55, -0.91, 0.74, 2.39]) {
    b.box([x, 0.97, 2.1], [0.16, 4.91, 0.18], '#8d613c');
    b.box([x, 0.97, -2.22], [0.16, 4.91, 0.18], '#8d613c');
  }
  for (const y of [1.08, 3.24, 5.61]) {
    b.box([-2.56, y, 2.12], [5.12, 0.16, 0.18], '#ab7b44');
    b.box([-2.56, y, -2.28], [5.12, 0.16, 0.18], '#92663e');
    b.box([2.43, y, -2.12], [0.17, 0.16, 4.24], '#ab7b44');
  }
  b.box([-0.77, 0.98, 2.126], [1.5, 2.16, 0.078], '#967046');
  for (let i = 0; i < 8; i++) b.box([-0.69 + i * 0.18, 1.05, 2.207], [0.065, 2.0, 0.04], '#c09961');
  b.box([-0.035, 1.13, 2.249], [0.07, 0.19, 0.029], '#705139');
  window(b, -2.26, 1.37, 2.14, 1.23, 1.45, true);
  window(b, 1.03, 1.37, 2.14, 1.23, 1.45, true);
  for (const x of [-2.16, -0.6, 0.98]) window(b, x, 3.74, 2.145, 1.16, 1.4, true);
  for (const z of [-1.66, 0.27]) {
    b.box([2.51, 1.62, z], [0.031, 1.12, 1.22], '#8b683d');
    b.box([2.545, 1.69, z + 0.07], [0.016, 0.98, 1.08], '#acccc0');
    b.box([2.51, 3.81, z], [0.031, 1.12, 1.22], '#8b683d');
    b.box([2.545, 3.88, z + 0.07], [0.016, 0.98, 1.08], '#d0d4b9');
  }
  b.box([-2.81, 3.2, 1.94], [5.62, 0.16, 0.67], '#40565b');
  for (let i = 0; i < 19; i++) b.box([-2.73 + i * 0.29, 3.36, 2.06], [0.045, 0.016, 0.43], '#6a7f7d');
  tileRoof(b, 5.86, 5.86, 4.73, P.roof);
  b.box([-2.66, 0.73, 2.42], [5.32, 0.15, 0.47], '#b5b099');
  b.box([-0.63, 0.73, 2.89], [1.26, 0.07, 0.43], '#d2c9ae');
  b.box([2.38, 5.93, -2.19], [0.081, 1.28, 0.082], '#69817b');
  b.box([2.38, 4.96, -2.19], [0.081, 0.98, 0.082], '#69817b');
  b.box([-2.36, 2.69, 2.29], [0.14, 0.2, 0.11], '#eed6a0', { glow: 0.35 });
  return b.finish('machiya');
}

